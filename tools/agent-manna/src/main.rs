fn cmd_update(request: UpdateRequest) -> ! {
    let UpdateRequest {
        id,
        title,
        description,
        status,
        issue_type,
        track,
        source,
        prompt,
    } = request;
    let store = MannaStore::new(Path::new("."));
    if !store.is_initialized() {
        output_error(
            "Storage not initialized. Run 'manna-core init' first.",
            EXIT_USER_ERROR,
        );
    }
    if title.is_none()
        && description.is_none()
        && status.is_none()
        && issue_type.is_none()
        && track.is_none()
        && source.is_none()
        && prompt.is_none()
    {
        output_error(
            "Nothing to update: pass --title, --description, --status, --type, --track, --source, or --prompt",
            EXIT_USER_ERROR,
        );
    }
    if status.is_some() {
        output_error(
            "update --status is disabled because it bypasses lifecycle ownership. Use claim, done, abandon, block, or unblock.",
            EXIT_USER_ERROR,
        );
    }
    let session = require_session_identity();
    let (issues, workflow) = load_board_workflow(&store);
    let before = find_issue(&issues, &id);
    if let Err(error) = before.require_owner(&session) {
        output_error(&error, EXIT_USER_ERROR);
    }
    let type_before = before.issue_type;
    let prompt_before = before.prompt.clone();
    let prompt_request = prompt.clone();
    let mut issue = before.clone();
    if let Some(new_title) = title {
        if new_title.is_empty() || new_title.len() > 500 {
            output_error("Title must be 1-500 characters", EXIT_USER_ERROR);
        }
        issue.title = new_title;
    }
    if let Some(new_description) = description {
        issue.description = if new_description.is_empty() {
            None
        } else {
            Some(new_description)
        };
    }
    if let Some(new_type) = issue_type {
        issue.issue_type = match parse_issue_type(&new_type) {
            Ok(t) => t,
            Err(e) => output_error(&e, EXIT_USER_ERROR),
        };
    }
    if let Some(new_track) = track {
        if new_track.is_empty() {
            issue.track = None;
        } else {
            if let Err(e) = validate_track_target(&issues, &new_track) {
                output_error(&e, EXIT_USER_ERROR);
            }
            issue.track = Some(new_track);
        }
    }
    if let Some(new_source) = source {
        issue.source = if new_source.is_empty() {
            None
        } else {
            Some(new_source)
        };
    }
    if let Some(new_prompt) = prompt {
        let trimmed = new_prompt.trim();
        if workflow.is_some()
            && trimmed.is_empty()
            && pairable(issue.issue_type)
            && (issue.issue_type == IssueType::Item || is_paired(&before))
        {
            output_error(
                "Strict workflow rows cannot clear their handoff pointer",
                EXIT_USER_ERROR,
            );
        }
        issue.prompt = if trimmed.is_empty() {
            None
        } else {
            Some(trimmed.to_string())
        };
    }
    if issue.issue_type == IssueType::Track && issue.track.is_some() {
        output_error(
            "Track issues cannot have a track edge (tracks don't nest)",
            EXIT_USER_ERROR,
        );
    }
    if issue.issue_type != type_before && before.claimed_by.is_some() {
        output_error(
            "Cannot convert a claimed issue. Finish or abandon the claim first.",
            EXIT_USER_ERROR,
        );
    }
    issue.updated_at = Utc::now();
    let authorization = conversion_authorization(&issue.id, type_before, issue.issue_type);

    let updated = if let Some(config) = workflow.as_ref() {
        let prompt_requested = prompt_request
            .as_deref()
            .map(str::trim)
            .filter(|value| !value.is_empty());
        // Pairing follows the row, not only its type: every strict item is
        // paired, a track is paired once it has a dispatch work order, and a
        // dream never is. The arms are (paired before, pairable after).
        match (is_paired(&before), pairable(issue.issue_type)) {
            (true, true) => {
                if let Some(requested) = prompt_requested {
                    if prompt_before.as_deref() != Some(requested) {
                        output_error(
                            "Strict workflow handoff pointers are stable; edit and seal the linked file instead of repointing the item",
                            EXIT_USER_ERROR,
                        );
                    }
                }
                issue.prompt = prompt_before.clone();
                let rebound = if type_before == issue.issue_type {
                    rebind_handoff_metadata(Path::new("."), &store, config, &before, &issue)
                } else {
                    // Item <-> track: the body's protocol differs by kind, so
                    // the document is regenerated under the same pointer.
                    regenerate_handoff(Path::new("."), &store, config, &before, &issue)
                };
                match rebound {
                    Ok(issue) => issue,
                    Err(error) => output_error(&error, EXIT_SYSTEM_ERROR),
                }
            }
            (false, true) => {
                issue.prompt = None;
                issue.handoff_digest = None;
                if type_before == IssueType::Track && issue.issue_type == IssueType::Track {
                    // A container track's metadata changes without acquiring
                    // a work order; `handoff attach` is the explicit act.
                    if prompt_requested.is_some() {
                        output_error(
                            &format!(
                                "A track takes its dispatch work order through `agent-do manna handoff attach {}`, not through update --prompt",
                                issue.id
                            ),
                            EXIT_USER_ERROR,
                        );
                    }
                    replace_metadata_atomically(&store, &before, &issue, &session)
                } else {
                    match attach_handoff(
                        Path::new("."),
                        &store,
                        config,
                        &before,
                        &issue,
                        prompt_request.as_deref(),
                    ) {
                        Ok(issue) => issue,
                        Err(error) => output_error(&error, EXIT_SYSTEM_ERROR),
                    }
                }
            }
            (true, false) => {
                if prompt_requested.is_some() {
                    output_error(
                        "Dreams cannot retain a strict handoff pointer",
                        EXIT_USER_ERROR,
                    );
                }
                match detach_handoff(Path::new("."), &store, config, &before, &issue) {
                    Ok(issue) => issue,
                    Err(error) => output_error(&error, EXIT_SYSTEM_ERROR),
                }
            }
            (false, false) => {
                if prompt_requested.is_some() {
                    output_error(
                        "Strict workflow boards pair handoffs with items and tracks, never dreams",
                        EXIT_USER_ERROR,
                    );
                }
                issue.prompt = None;
                issue.handoff_digest = None;
                replace_metadata_atomically(&store, &before, &issue, &session)
            }
        }
    } else {
        if let Some(new_prompt) = prompt_request {
            let trimmed = new_prompt.trim();
            issue.prompt = (!trimmed.is_empty()).then(|| trimmed.to_string());
        }
        replace_metadata_atomically(&store, &before, &issue, &session)
    };
    output_success(UpdateData {
        issue: updated,
        authorization,
    });
}

fn replace_metadata_atomically(
    store: &MannaStore,
    before: &Issue,
    after: &Issue,
    session: &SessionIdentity,
) -> Issue {
    let expected = before.clone();
    let replacement = after.clone();
    match store.mutate_issue_metadata(&before.id, session, move |current, issues| {
        if current != &expected {
            return Err(format!(
                "{} changed concurrently; retry the update",
                current.id
            ));
        }
        if let Some(track_id) = replacement.track.as_deref() {
            validate_track_target(issues, track_id)?;
        }
        *current = replacement;
        Ok(())
    }) {
        Ok(issue) => issue,
        Err(error) => handle_manna_error(error),
    }
}

/// The line `update` prints when a type change crosses the dream boundary.
///
/// Conversion is the authorization act, so it is stated out loud in both
/// directions rather than left to be inferred from a changed field.
fn conversion_authorization(id: &str, before: IssueType, after: IssueType) -> Option<String> {
    match (before, after) {
        (IssueType::Dream, IssueType::Item) | (IssueType::Dream, IssueType::Track) => Some(format!(
            "AUTHORIZED: {} converted dream -> {}. It is now claimable work: agent-do manna claim {}",
            id, after, id
        )),
        (_, IssueType::Dream) if before != IssueType::Dream => Some(format!(
            "PARKED: {} converted {} -> dream. It is no longer claimable; convert it back with \
             agent-do manna update {} --type item before any agent works it.",
            id, before, id
        )),
        _ => None,
    }
}

