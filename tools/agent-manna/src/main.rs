/// Load the pinned, authenticated session identity used for ownership.
///
/// Per-process fallbacks make separate `claim` and `done` invocations appear
/// to be different sessions. They also turn a visible owner label into a
/// forgeable credential. Mutations therefore fail closed unless both values
/// were pinned explicitly or an agent host supplies an opaque runtime identity
/// whose proof can be derived under the machine-local Manna key.
fn get_session_identity() -> Result<SessionIdentity, String> {
    // Empty counts as unset: hooks neutralize a stale half-pinned pair by
    // blanking it, so derivation below can take over after a restart.
    let id = std::env::var("MANNA_SESSION_ID")
        .ok()
        .filter(|value| !value.trim().is_empty());
    let token = std::env::var("MANNA_SESSION_TOKEN")
        .ok()
        .filter(|value| !value.trim().is_empty());
    match (id, token) {
        (Some(id), Some(token)) => return SessionIdentity::from_token(&id, &token),
        (Some(_), None) => {
            return Err(
                "MANNA_SESSION_ID is pinned but MANNA_SESSION_TOKEN is missing; ownership requires both values. Restart-durable alternative: unset MANNA_SESSION_ID and export CLAUDE_SESSION_ID — its proof re-derives under the machine-local key after any process restart"
                    .to_string(),
            )
        }
        (None, Some(_)) => {
            return Err(
                "MANNA_SESSION_TOKEN is pinned but MANNA_SESSION_ID is missing; ownership requires both values"
                    .to_string(),
            )
        }
        (None, None) => {}
    }

    // Codex cannot persist arbitrary environment returned by SessionStart,
    // but it does pin one opaque thread identifier across every shell. Derive
    // a private proof under a machine-local key while exposing only coord's
    // compact public label. The same pattern covers hosts that provide their
    // own opaque Claude identity when the Claude env-file hook is unavailable.
    for (runtime, variable) in [
        ("codex", "CODEX_THREAD_ID"),
        ("claude", "CLAUDE_THREAD_ID"),
        ("claude", "CLAUDE_SESSION_ID"),
        ("claude", "CLAUDE_AGENT_ID"),
    ] {
        if let Ok(opaque_id) = std::env::var(variable) {
            if !opaque_id.trim().is_empty() {
                return runtime_session_identity(runtime, &opaque_id);
            }
        }
    }

    // The human at the keyboard. No agent runtime pinned anything and stdin
    // is a terminal, so this is the operator's own shell: derive a proof under
    // the same machine-local key, labelled by login name. Agent hosts run
    // their shells on pipes and never reach this branch. `MANNA_OPERATOR=0`
    // opts a terminal out (a script that must act as a pinned lane).
    if operator_fallback_enabled() {
        if let Some(user) = operator_user() {
            return runtime_session_identity("operator", &user).map(SessionIdentity::into_operator);
        }
    }

    Err(
        "Manna session identity is not pinned; start through an agent-do session hook, run from your own terminal (operator identity), or export both MANNA_SESSION_ID and a secret MANNA_SESSION_TOKEN"
            .to_string(),
    )
}

/// True when the operator derivation may run: stdin is a terminal and the
/// operator has not opted out with `MANNA_OPERATOR=0`.
fn operator_fallback_enabled() -> bool {
    use std::io::IsTerminal;
    if std::env::var("MANNA_OPERATOR")
        .ok()
        .is_some_and(|value| value.trim() == "0")
    {
        return false;
    }
    std::io::stdin().is_terminal()
}

/// The login name the operator identity is labelled by.
fn operator_user() -> Option<String> {
    ["USER", "LOGNAME"]
        .into_iter()
        .filter_map(|name| std::env::var(name).ok())
        .map(|value| value.trim().to_string())
        .find(|value| !value.is_empty())
}

fn require_session_identity() -> SessionIdentity {
    get_session_identity().unwrap_or_else(|error| output_error(&error, EXIT_NEEDS_AUTHORIZATION))
}

fn current_session_label() -> Option<String> {
    if let Ok(id) = std::env::var("MANNA_SESSION_ID") {
        if !id.trim().is_empty() {
            return Some(id);
        }
    }
    for (runtime, variable) in [
        ("codex", "CODEX_THREAD_ID"),
        ("claude", "CLAUDE_THREAD_ID"),
        ("claude", "CLAUDE_SESSION_ID"),
        ("claude", "CLAUDE_AGENT_ID"),
    ] {
        if let Ok(opaque_id) = std::env::var(variable) {
            if let Ok(label) = runtime_session_label(runtime, &opaque_id) {
                return Some(label);
            }
        }
    }
    if operator_fallback_enabled() {
        if let Some(label) =
            operator_user().and_then(|user| runtime_session_label("operator", &user).ok())
        {
            return Some(label);
        }
    }
    None
}

/// Output success response as YAML and exit with success code.
fn output_success<T: Serialize>(data: T) -> ! {
    let response = SuccessResponse {
        success: true,
        data,
    };
    println!(
        "{}",
        serde_yaml::to_string(&response).unwrap_or_else(|e| {
            format!("success: false\nerror: \"YAML serialization error: {}\"", e)
        })
    );
    std::process::exit(EXIT_SUCCESS);
}

/// Output success response as JSON and exit with success code.
fn output_success_json<T: Serialize>(data: T) -> ! {
    let response = SuccessResponse {
        success: true,
        data,
    };
    println!(
        "{}",
        serde_json::to_string(&response).unwrap_or_else(|e| {
            format!(
                "{{\"success\":false,\"error\":\"JSON serialization error: {}\"}}",
                e
            )
        })
    );
    std::process::exit(EXIT_SUCCESS);
}

/// Print a success-shaped response and exit with the given code.
///
/// Lint and reconcile are gates: the body reports findings, the exit code
/// carries the verdict, so they cannot use output_success (always 0).
fn output_with_exit<T: Serialize>(data: T, json: bool, exit_code: i32) -> ! {
    let response = SuccessResponse {
        success: true,
        data,
    };
    if json {
        println!(
            "{}",
            serde_json::to_string(&response).unwrap_or_else(|e| {
                format!(
                    "{{\"success\":false,\"error\":\"JSON serialization error: {}\"}}",
                    e
                )
            })
        );
    } else {
        println!(
            "{}",
            serde_yaml::to_string(&response).unwrap_or_else(|e| {
                format!("success: false\nerror: \"YAML serialization error: {}\"", e)
            })
        );
    }
    std::process::exit(exit_code);
}

