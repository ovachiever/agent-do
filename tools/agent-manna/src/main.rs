/// Convert MannaError to exit code.
fn error_to_exit_code(err: &MannaError) -> i32 {
    match err {
        MannaError::IssueNotFound(_) => EXIT_USER_ERROR,
        MannaError::IssueAlreadyExists(_) => EXIT_USER_ERROR,
        MannaError::InvalidStatusTransition { .. } => EXIT_USER_ERROR,
        MannaError::InvalidId(_) => EXIT_USER_ERROR,
        MannaError::MutationRejected(_) => EXIT_USER_ERROR,
        MannaError::RecoveryConflict(_) => EXIT_USER_ERROR,
        MannaError::Io(_) => EXIT_SYSTEM_ERROR,
        MannaError::Json(_) => EXIT_SYSTEM_ERROR,
        MannaError::NotInitialized => EXIT_USER_ERROR,
        MannaError::LockFailed(_) => EXIT_SYSTEM_ERROR,
    }
}

/// Handle MannaError by outputting YAML error and exiting.
fn handle_manna_error(err: MannaError) -> ! {
    let exit_code = error_to_exit_code(&err);
    output_error(&err.to_string(), exit_code);
}

/// Parse status string to IssueStatus.
fn parse_status(s: &str) -> Result<IssueStatus, String> {
    match s.to_lowercase().as_str() {
        "open" => Ok(IssueStatus::Open),
        "in_progress" => Ok(IssueStatus::InProgress),
        "blocked" => Ok(IssueStatus::Blocked),
        "done" => Ok(IssueStatus::Done),
        _ => Err(format!(
            "Invalid status '{}'. Valid options: open, in_progress, blocked, done",
            s
        )),
    }
}

/// Parse issue type string to IssueType.
fn parse_issue_type(s: &str) -> Result<IssueType, String> {
    match s.to_lowercase().as_str() {
        "track" => Ok(IssueType::Track),
        "item" => Ok(IssueType::Item),
        "dream" => Ok(IssueType::Dream),
        _ => Err(format!(
            "Invalid type '{}'. Valid options: track, item, dream",
            s
        )),
    }
}

/// Validate that a --track target exists on the board and is a track.
fn validate_track_target(issues: &[Issue], track_id: &str) -> Result<(), String> {
    match issues.iter().find(|i| i.id == track_id) {
        None => Err(format!("Track {} not found", track_id)),
        Some(target) if target.issue_type != IssueType::Track => Err(format!(
            "Issue {} is not a track (type: {})",
            track_id, target.issue_type
        )),
        Some(_) => Ok(()),
    }
}

/// Find issue by ID or exit with error.
fn find_issue(issues: &[Issue], id: &str) -> Issue {
    issues
        .iter()
        .find(|i| i.id == id)
        .cloned()
        .unwrap_or_else(|| {
            output_error(&issue_not_found_message(id), EXIT_USER_ERROR);
        })
}

/// "Not found" that names where the id actually lives. The wrong checkout is
/// the common cause, and the estate registry already knows every board.
fn issue_not_found_message(id: &str) -> String {
    match locate_issue_on_registered_boards(id) {
        Some((board, root)) => format!(
            "Issue {} not found on this board; it lives on {} ({}). Run the command from that checkout.",
            id, board, root
        ),
        None => format!("Issue {} not found", id),
    }
}

/// Search every registered board except the current one for an issue id.
/// Returns the first (board name, root) that holds it. Read-only, and a
/// missing or unreadable registry is simply no answer.
fn locate_issue_on_registered_boards(id: &str) -> Option<(String, String)> {
    let home = std::env::var_os("AGENT_DO_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|home| PathBuf::from(home).join(".agent-do")))?;
    let text = std::fs::read_to_string(home.join("manna/serve/boards.json")).ok()?;
    let registry: serde_json::Value = serde_json::from_str(&text).ok()?;
    let here = Path::new(".").canonicalize().ok();
    let mut boards = registry
        .get("boards")?
        .as_object()?
        .iter()
        .filter_map(|(name, entry)| {
            entry
                .get("path")
                .and_then(serde_json::Value::as_str)
                .map(|root| (name.clone(), root.to_string()))
        })
        .collect::<Vec<_>>();
    boards.sort();
    for (name, root) in boards {
        let root_path = Path::new(&root);
        if here
            .as_ref()
            .zip(root_path.canonicalize().ok())
            .is_some_and(|(here, there)| here == &there)
        {
            continue;
        }
        let Ok(rows) = std::fs::read_to_string(root_path.join(".manna/issues.jsonl")) else {
            continue;
        };
        let held = rows.lines().any(|line| {
            serde_json::from_str::<serde_json::Value>(line)
                .ok()
                .and_then(|row| {
                    row.get("id")
                        .and_then(serde_json::Value::as_str)
                        .map(str::to_string)
                })
                .is_some_and(|row_id| row_id == id)
        });
        if held {
            return Some((name, root));
        }
    }
    None
}

fn load_board_workflow(store: &MannaStore) -> (Vec<Issue>, Option<WorkflowConfig>) {
    if let Err(error) = store.validate_storage_root() {
        handle_manna_error(error);
    }
    if let Err(error) = recover_legacy_migration(Path::new("."), store) {
        output_error(
            &format!("Cannot recover Manna legacy migration: {}", error),
            EXIT_SYSTEM_ERROR,
        );
    }
    let mut issues = match store.load_issues() {
        Ok(issues) => issues,
        Err(error) => handle_manna_error(error),
    };
    let workflow = match load_workflow_for_board(Path::new("."), &issues) {
        Ok(config) => config,
        Err(error) => output_error(&error, EXIT_SYSTEM_ERROR),
    };
    if let Some(config) = workflow.as_ref() {
        if let Err(error) = validate_scaffold(Path::new("."), config) {
            output_error(&error, EXIT_SYSTEM_ERROR);
        }
        if let Err(error) = recover_pair_transactions(Path::new("."), store, config) {
            output_error(
                &format!("Cannot recover Manna workflow transaction: {}", error),
                EXIT_SYSTEM_ERROR,
            );
        }
        issues = match store.load_issues() {
            Ok(issues) => issues,
            Err(error) => handle_manna_error(error),
        };
    }
    if let Err(error) = federation::recover_transaction(Path::new("."), store) {
        output_error(
            &format!("Cannot recover Manna federation transaction: {}", error),
            EXIT_SYSTEM_ERROR,
        );
    }
    (issues, workflow)
}

