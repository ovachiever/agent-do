fn cmd_list(
    status_filter: Option<String>,
    type_filter: Option<String>,
    track_filter: Option<String>,
    json: bool,
) -> ! {
    let store = MannaStore::new(Path::new("."));

    if !store.is_initialized() {
        output_error(
            "Storage not initialized. Run 'manna-core init' first.",
            EXIT_USER_ERROR,
        );
    }

    // Load issues
    let issues = match store.load_issues() {
        Ok(i) => i,
        Err(err) => handle_manna_error(err),
    };

    // Parse filters if provided
    let filter: Option<IssueStatus> = match status_filter {
        Some(s) => match parse_status(&s) {
            Ok(status) => Some(status),
            Err(e) => output_error(&e, EXIT_USER_ERROR),
        },
        None => None,
    };
    let type_filter: Option<IssueType> = match type_filter {
        Some(s) => match parse_issue_type(&s) {
            Ok(t) => Some(t),
            Err(e) => output_error(&e, EXIT_USER_ERROR),
        },
        None => None,
    };

    // Filter and map to summaries
    let summaries: Vec<IssueSummary> = issues
        .into_iter()
        .filter(|i| filter.as_ref().is_none_or(|f| &i.status == f))
        .filter(|i| type_filter.is_none_or(|f| i.issue_type == f))
        .filter(|i| {
            track_filter
                .as_ref()
                .is_none_or(|f| i.track.as_ref() == Some(f))
        })
        .map(|i| IssueSummary {
            gate: (i.issue_type == IssueType::Dream).then(|| DREAM_INERT_MARKER.to_string()),
            updated: dated(i.updated_at),
            id: i.id,
            title: i.title,
            status: i.status,
            claimed_by: i.claimed_by,
            issue_type: i.issue_type,
            track: i.track,
        })
        .collect();

    if json {
        output_success_json(IssueListData { issues: summaries });
    }
    output_success(IssueListData { issues: summaries });
}

fn cmd_state(json: bool, decision_markers: Vec<String>, cached_drift: bool) -> ! {
    let root = match std::env::current_dir() {
        Ok(root) => root,
        Err(error) if json => output_error_json(
            &format!("Cannot resolve current directory: {error}"),
            EXIT_SYSTEM_ERROR,
        ),
        Err(error) => output_error(
            &format!("Cannot resolve current directory: {error}"),
            EXIT_SYSTEM_ERROR,
        ),
    };
    let mut options = StateOptions::default();
    for marker in decision_markers {
        let marker = marker.trim().to_string();
        if !(marker.starts_with('[') && marker.ends_with(']') && marker.len() > 2) {
            let error =
                format!("A decision marker is a bracketed tag like [OWNER], not {marker:?}");
            if json {
                output_error_json(&error, EXIT_USER_ERROR);
            }
            output_error(&error, EXIT_USER_ERROR);
        }
        if !options
            .decision_markers
            .iter()
            .any(|existing| existing.eq_ignore_ascii_case(&marker))
        {
            options.decision_markers.push(marker);
        }
    }
    if options.decision_markers.is_empty() {
        options.decision_markers = DEFAULT_DECISION_MARKERS
            .iter()
            .map(|marker| marker.to_string())
            .collect();
    }
    if cached_drift {
        options.live_drift = false;
    }
    let state = match derive_board_state(&root, &options) {
        Ok(state) => state,
        Err(error) if json => output_error_json(&error, EXIT_SYSTEM_ERROR),
        Err(error) => output_error(&error, EXIT_SYSTEM_ERROR),
    };
    if json {
        output_success_json(state);
    }
    output_success(state);
}

